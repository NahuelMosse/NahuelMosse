export const BEGIN = '<!-- close.mjs:begin · regenerated by `node .claude/tools/close.mjs`; what is written inside is lost on the next run -->';
export const END = '<!-- close.mjs:end -->';
export const FOOTER = '🤖 Generated with [Claude Code](https://claude.com/claude-code)';

// The seal binds the block to the gate records it was written from and to the card: a closing.md written by hand, or edited
// after the close, does not carry a seal publish can recompute, so it cannot unlock a merge. Not a signature, a consistency mark.
export const SEAL = /^close\.mjs seal: (\S+) sha256:([0-9a-f]{64})$/m;
const gateRecords = (root, cardDir) => {
  const doc = readCard(cardDir) ?? '';
  if (!gateBlock(doc)) return [];
  const base = cardStart(root, cardDir);
  return (planCommands(doc, { base, cardDir }, 'Gate') ?? []).map((c) => [c.name, readRecord(root, c.name, c.command)]);
};
export const sealOf = (root, cardDir, body) => createHash('sha256')
  .update(`${cardIdOf(cardDir)}\n${JSON.stringify(gateRecords(root, cardDir))}\n${body.replace(/\r\n?/g, '\n')}`).digest('hex');
const sealLine = (root, cardDir, body) => `close.mjs seal: ${cardIdOf(cardDir)} sha256:${sealOf(root, cardDir, body)}`;
// Whether closing.md carries a seal of this card that matches its block and the gate records as they are now.
export const sealed = (root, cardDir, text) => {
  const t = text.replace(/\r\n?/g, '\n');
  const from = t.indexOf(BEGIN);
  const m = from < 0 ? null : SEAL.exec(t.slice(from));
  if (!m) return false;
  return m[1] === cardIdOf(cardDir) && m[2] === sealOf(root, cardDir, t.slice(from, from + m.index));
};

// What a poc's capture round has to prove ran: a round on a dealt or taken brand sheet (gate-checks.mjs `brand`).
const POC_PROOF = new Set(['brand']);
const PLAN_FILE = /^[\w@.-]+(?:\/[\w@.-]+)*\.(?:m?[jt]sx?|cjs|cts|py|go|cs|java|kt|rb|php|dart|html?|s?css|vue|svelte|sql|md|json|ya?ml|sh|feature)$/;
const TEST_SOURCE = /\.(m?[jt]sx?|cjs|cts|py|go|cs|java|kt|rb|php|dart|feature|c|cc|cpp|cxx|rs|swift)$/;
const BINARY_EXTENSIONS = ['png', 'jpg', 'jpeg', 'gif', 'webp', 'avif', 'ico', 'mp4', 'webm', 'mov', 'mp3', 'wav', 'pdf', 'zip', 'gz', 'woff', 'woff2', 'ttf', 'otf', 'glb', 'bin'];
const escape = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const textOf = (path) => (existsSync(path) ? readFileSync(path, 'utf8') : '');

// The versioned test files that carry a spec tag of the card, at `rev` or in the working tree.
const taggedFiles = (root, id, rev = null) => {
  const found = git(root, ['grep', '-l', '-I', '-E', `@(assumption:)?${id}-(S|ASM-)[0-9]+`, ...(rev ? [rev] : []), '--', ':(exclude)specs', ':(exclude).claude']);
  if (found.status !== 0) return [];
  return found.stdout.split('\n').filter(Boolean).map((l) => (rev ? l.slice(rev.length + 1) : l)).filter((f) => TEST_SOURCE.test(f));
};

// What critique.md says: the lowest score it gives (`polish:`, `motion:`, the number after `→` in `Total:`) and its open blockers
// (`Blocker: <text>` lines that are not «none» and do not say closed or resolved), and the rubric lines it could not see
// (`not inspected`), which the close names so the PR does not read them as passed.
export const critiqueOf = (text) => {
  const notInspected = text.split('\n').filter((l) => /\bnot inspected\b/i.test(l))
    .map((l) => l.replace(/^[\s\-*#]+/, '').replace(/\*\*/g, '').trim());
  const scores = [
    ...[...text.matchAll(/^\W*(?:polish|motion)\W*:\s*(\d+(?:[.,]\d+)?)/gim)].map((m) => Number(m[1].replace(',', '.'))),
    ...[...text.matchAll(/^\W*Total\b[^\n]*?→\s*(\d+(?:[.,]\d+)?)/gim)].map((m) => Number(m[1].replace(',', '.'))),
  ];
  const blockers = [...text.matchAll(/^\W*Blockers?\W*:[ \t*_]*(.+)$/gim)].map((m) => m[1].trim())
    .filter((b) => !/^(?:none|ninguno|ninguna|no|-|—|n\/a)\b/i.test(b) && !/\b(?:closed|resolved|cerrado|resuelto)\b/i.test(b));
  return { score: scores.length ? Math.min(...scores) : null, blockers, notInspected };
};

const runOnce = (root, { write = true } = {}) => {
  const cardDir = currentCard(root);
  if (!cardDir) return null;
  const id = cardIdOf(cardDir);
  const card = basename(cardDir);
  const doc = readCard(cardDir) ?? '';
  const rel = (f) => relativeTo(root, join(cardDir, f));
  const checks = [];
  const add = (n, label, state, detail = '') => checks.push({ n, label, state, detail });
  const verdict = (n, label, bad, ok = '') => add(n, label, bad.length ? 'failed' : 'passed', bad.length ? bad.join('; ') : ok);

  // 1. L1 intact since the commit that froze card.md
  // The commit that added card.md and its date, which also dates the start of the card for the cost.
  const [first, since = null] = git(root, ['log', '--diff-filter=A', '--format=%H %aI', '--', rel('card.md')]).stdout?.trim().split('\n').filter(Boolean).at(-1)?.split(' ') ?? [];
  if (!first) add(1, 'L1 intact', 'could not run', `${rel('card.md')} is not committed yet: nothing froze it`);
  else {
    const then = git(root, ['show', `${first}:${rel('card.md')}`]);
    if (then.status !== 0) add(1, 'L1 intact', 'could not run', `git show ${first}:${rel('card.md')} failed`);
    else verdict(1, 'L1 intact', requirementOf(then.stdout).trim() === requirementOf(doc).trim() ? [] : [`L1 of ${rel('card.md')} changed since ${first.slice(0, 9)}`], `unchanged since ${first.slice(0, 9)}`);
  }

  // At poc the close is short: L1, the capture round (the checks verify.mjs adds) and a closing of what was shown.
  const { off, grade, manifest, exempt } = active(root);
  if (isPoc(root)) {
    const why = 'poc: a facade, no tests, no gate, no judge';
    for (const [n, label] of [[2, 'every spec has a test'], [3, 'every tag is a spec of card.md'], [4, 'each ASM is tagged or declared uncovered'], [5, 'no tagged test touched since RED'], [6, 'diff and Tasks agree']]) add(n, label, 'skipped', why);
    // The capture round is all a poc proves: a round never run on a dealt sheet, or with no reference captured, is not a pass.
    const bad = gateChecks(root, cardDir).filter((c) => c.name !== 'specs' && (c.state === 'failed' || (POC_PROOF.has(c.name) && c.state === 'could not run'))).map((c) => `${c.name}: ${c.detail}`);
    verdict(7, 'capture round', bad, 'the capture round passed');
    for (const [n, label] of [[8, 'judge'], [9, 'required.mjs']]) add(n, label, 'skipped', why);
    const result = { cardDir, checks, wrote: [], closing: null, off: [...off].map(([name, o]) => ({ name, reason: o.reason })) };
    if (write) result.closing = writeClosing(root, cardDir, { poc: true, card, doc, base: null, off, grade, manifest, checks, since, risk: null, acts: [], asms: [], untagged: [] });
    return result;
  }

  // 2 to 5. specs, tags, assumptions, frozen tests
  const spec = specsCheck(root, cardDir);
  add(2, 'every spec has a test', spec.state, spec.detail);
  const tagged = id ? taggedFiles(root, id) : [];
  const specIds = new Set([...(sectionOf(doc, 'Specs') ?? '').matchAll(/^\s*(?:[-*]\s*)?(S\d+)\b/gm)].map((m) => m[1]));
  const strangers = [...new Set(tagged.flatMap((f) => specTagsIn(id, textOf(join(root, f)))))].filter((s) => !specIds.has(s)).sort();
  add(3, 'every tag is a spec of card.md', strangers.length ? 'failed' : 'passed', strangers.length ? strangers.map((s) => `@${id}-${s} is not in ## Specs`).join('; ') : `${tagged.length} tagged file${tagged.length === 1 ? '' : 's'}`);

  const asms = [...new Set((sectionOf(doc, 'Specs') ?? '').match(/[A-Z][A-Z0-9]*-\d+[A-Za-z0-9]*-ASM-\d+/g) ?? [])];
  const testText = tagged.map((f) => textOf(join(root, f))).join('\n');
  const log = doc.split(/^## Log\b.*$/m)[1] ?? '';
  const untagged = asms.filter((a) => !new RegExp(`@(?:assumption:)?${escape(a)}(?!\\d)`).test(testText));
  verdict(4, 'each ASM is tagged or declared uncovered', untagged.filter((a) => !new RegExp(`uncovered[^\\n]*${escape(a)}|${escape(a)}[^\\n]*uncovered`, 'i').test(log))
    .map((a) => `${a} has no \`@${a}\` test and no \`uncovered\` line in the Log`), `${asms.length - untagged.length} of ${asms.length} tagged${untagged.length ? `; declared uncovered: ${untagged.join(', ')}` : ''}`);

  // Searched only from the card's start and never in binaries: over a whole history of images the pickaxe took 4 min 47 s.
  // A start without `~1` is the root commit, which a `<start>..HEAD` range would leave out: the whole history is searched then.
  const start = id ? cardStart(root, cardDir) : 'HEAD';
  const red = id ? git(root, ['log', '--reverse', '--format=%H', '-G', `@${id}-S[0-9]+`, ...(start.endsWith('~1') ? [`${start}..HEAD`] : []), '--', '.', ':(exclude)specs', ':(exclude).claude',
    ...BINARY_EXTENSIONS.map((ext) => `:(exclude,glob)**/*.${ext}`)]).stdout?.trim().split('\n').filter(Boolean)[0] : null;
  if (exempt.level?.testsFrozen === false) add(5, 'no tagged test touched since RED', 'skipped', `the grade ${grade} leaves committed tests editable`);
  else if (!red) add(5, 'no tagged test touched since RED', 'could not run', 'no commit holds tests tagged for this card');
  else {
    const atRed = taggedFiles(root, id, red);
    const diff = git(root, ['diff', '--name-only', '--diff-filter=MDRT', `${red}..HEAD`, '--', ...atRed.map((f) => `:(literal)${f}`)]);
    const refactor = gateBlock(readCard(cardDir) ?? '')?.match(/^\s*refactor-tests\s*:\s*(\S.*)$/m)?.[1]?.trim();
    const touched = diff.status === 0 ? diff.stdout.split('\n').filter(Boolean) : [];
    if (diff.status !== 0) add(5, 'no tagged test touched since RED', 'could not run', `git diff ${red.slice(0, 9)}..HEAD failed: ${diff.stderr?.trim()}`);
    // A declared refactor edits frozen tests in place: it passes, and every touched file goes to a person (## Needs a person).
    else if (refactor) add(5, 'no tagged test touched since RED', 'passed', `declared refactor-tests: ${refactor}; ${touched.length} file${touched.length === 1 ? '' : 's'} tagged for ${id} edited since RED; the frozen tests of earlier cards it edited are listed in ## Needs a person`);
    else verdict(5, 'no tagged test touched since RED', diff.stdout.split('\n').filter(Boolean).map((f) => `${f} changed since ${red.slice(0, 9)}`), `none of ${atRed.length} tagged file${atRed.length === 1 ? '' : 's'} since ${red.slice(0, 9)}`);
  }

  // 6. the diff and the Tasks, both directions
  const base = cardStart(root, cardDir);
  const map = fileMapLines(cardDir);
  if (!map) add(6, 'diff and Tasks agree', 'could not run', 'card.md has no ## Tasks');
  else {
    const diff = cardFiles(root, base);
    const outside = diff.filter((f) => !NOT_PRODUCTION.test(f) && !namedIn(map, f, root).length && !copiedFromKit(root, map, f)).map((f) => `${f} is in the diff, not in Tasks`);
    const kitFile = (t) => t.startsWith('.claude/') || (!t.includes('/') && existsSync(join(root, '.claude', 'tools', t)));
    const named = [...new Set(map.flatMap(taskTokens).filter((t) => PLAN_FILE.test(t) && !kitFile(t)))];
    // A file the plan named and the work did not need to touch is a note, not a failure: the code outside the plan is what
    // matters. Measured: 22 refusals in one repo, each answered by a commit that only took the file out of Tasks.
    const absent = named.filter((t) => !diff.some((f) => f === t || f.endsWith(`/${t}`))).map((t) => `${t} is in Tasks, not in the diff`);
    verdict(6, 'diff and Tasks agree', outside, `${diff.length} files in the diff against ${base}${absent.length ? `; ${absent.join('; ')}` : ''}`);
  }

  // The session line before 9: nothing asks for it any more, but the record of where the session lives is kept.
  const wrote = [];
  if (write) for (const _ of writeSessionLines(root, cardDir)) wrote.push(rel('sessions.md'));

  // 7. the gate: every line of `## Gate` passed on this code
  const gate = gateBlock(doc) ? planCommands(doc, { base, cardDir }, 'Gate') ?? [] : [];
  if (!gate.length) add(7, 'gate green', 'could not run', 'card.md has no ## Gate with a block of commands');
  else {
    const gateLines = gate.filter((c) => !skippedBy(c, exempt, map ?? [], root));
    // A line planned as unrunnable (nothing to hand `{affected}`) is reported under `## Could not run`, not as a failure.
    const unrunnable = gateLines.filter((c) => c.cannotRun);
    const lines = gateLines.filter((c) => !c.cannotRun);
    for (const c of unrunnable) add(7, `gate line ${c.name}`, 'could not run', c.cannotRun);
    const bad = lines.flatMap((c) => {
      const r = readRecord(root, c.name, c.command);
      if (!r) return [`${c.name}: no record: run \`node .claude/tools/verify.mjs\``];
      if (r.exit !== 0 && !(r.exit === 3 && c.file !== undefined)) return [`${c.name}: exit ${r.exit}`];
      return r.key === keyOf(root, c.command) ? [] : [`${c.name}: ran on other code: run verify.mjs again`];
    });
    // The checks verify.mjs adds to the lines (busy, lang…) leave no record: a failed one fails the gate here too.
    bad.push(...gateChecks(root, cardDir).filter((c) => c.name !== 'specs' && c.state === 'failed').map((c) => `${c.name}: ${c.detail}`));
    verdict(7, 'gate green', bad, `${lines.length} line${lines.length === 1 ? '' : 's'} passed on this code${gate.length > lines.length ? `, ${gate.length - lines.length} skipped by grade ${grade}` : ''}`);
  }

  // 8. the judge, by risk
  const risk = riskOf(cardDir);
  const judgeText = textOf(join(cardDir, 'judge.md'));
  const acts = actsOf(judgeText);
  if (!risk) add(8, 'judge', 'could not run', `no risk.json: \`node .claude/tools/risk.mjs ${relativeTo(root, cardDir)}\``);
  else if (risk.review !== 'high' && !existsSync(join(cardDir, 'judge.md'))) add(8, 'judge', 'skipped', `risk.json says review: ${risk.review}`);
  else if (exempt.without?.has('judge') && !existsSync(join(cardDir, 'judge.md'))) add(8, 'judge', 'skipped', `the grade ${grade} launches no judge`);
  else if (!existsSync(join(cardDir, 'judge.md'))) add(8, 'judge', 'failed', `risk.json says review: high and ${rel('judge.md')} does not exist`);
  else verdict(8, 'judge', [...acts.flatMap((a) => { const why = actHold(a, doc); return why ? [`${a.id} is ${why}`] : []; })], `${acts.length} ACT${acts.some((a) => a.plan) ? ` (${acts.filter((a) => a.plan).length} of plan)` : ''}, every one closed or declared`);

  // 9. what the diff makes necessary
  try { verdict(9, 'required.mjs', missing(root, { closing: false }) ?? [], 'mutation, linter and scope ran and passed on this code'); } catch (e) { add(9, 'required.mjs', 'could not run', e.message); }

  // 10. the critic of the look, when the card has a critique.md: a score under 7, an open blocker or a critique older than the screen is not a pass
  if (existsSync(join(cardDir, 'critique.md'))) {
    const { score, blockers, notInspected } = critiqueOf(textOf(join(cardDir, 'critique.md')));
    const bad = [];
    if (score === null) bad.push(`${rel('critique.md')} gives no score (\`polish: N\`)`);
    else if (score < 7) bad.push(`score ${score} is under 7`);
    for (const b of blockers) bad.push(`open blocker: ${b.length > 160 ? `${b.slice(0, 160)}…` : b}`);
    const at = git(root, ['log', '-1', '--format=%H', '--', rel('critique.md')]).stdout?.trim();
    const screens = [...rolesOf(doc)].filter(([, role]) => role === 'presentation').map(([f]) => f);
    let note = '';
    if (!at) note = ' (critique.md is not committed: its age against the screen is not known)';
    else if (screens.length) {
      const after = git(root, ['log', '--format=%h', `${at}..HEAD`, '--', ...screens.map((f) => `:(literal)${f}`)]).stdout?.split('\n').filter(Boolean) ?? [];
      const dirty = git(root, ['status', '--porcelain', '--', ...screens.map((f) => `:(literal)${f}`)]).stdout?.trim();
      if (after.length || dirty) bad.push(`the critique is stale: presentation files changed after ${at.slice(0, 9)} (${after.length ? `${after.length} commit${after.length === 1 ? '' : 's'}` : 'uncommitted changes'}); it cannot pass the card on that critique`);
    }
    if (notInspected.length) note += `; not inspected: ${notInspected.map((l) => (l.length > 120 ? `${l.slice(0, 120)}…` : l)).join(' · ')}`;
    verdict(10, 'critique', bad, `score ${score}, no open blocker, no presentation change after ${at ? at.slice(0, 9) : 'it'}${note}`);
  } else if (risk?.lenses?.includes('visual') && grade === 'production' && !exempt.without?.has('design-critic') && !noLookOf(doc)) {
    // METHOD step 3 launches the critic; a visual card at production without its critique.md is a look nobody judged.
    // A remove-only or a plain card adds no look to judge.
    add(10, 'critique', 'could not run', `no ${rel('critique.md')}: the design-critic never looked at this screen; launch it with the path of card.md and the URL of the app before the close`);
  }

  const result = { cardDir, checks, wrote, closing: null, off: [...off].map(([name, o]) => ({ name, reason: o.reason })) };
  if (write) result.closing = writeClosing(root, cardDir, { card, doc, risk, acts, asms, untagged, base, off, grade, manifest, checks, since });
  return result;
};
// One round: every check of the close shares one listing of the card's files and one start (card.mjs, `oneRound`).
export const run = (root, options = {}) => oneRound(() => runOnce(root, options));

const bullets = (checks, state) => {
  const lines = checks.filter((c) => (state === 'passed' ? ['passed', 'skipped'] : [state]).includes(c.state))
    .map((c) => `- ${c.n} · ${c.label}${c.state === 'skipped' ? ' · skipped' : ''}${c.detail ? ` — ${c.detail}` : ''}`);
  return lines.length ? lines.join('\n') : 'none';
};

const judgeSummary = (risk, acts) => {
  if (!risk) return 'no risk.json: the card was not classified';
  if (risk.review !== 'high' && !acts.length) return `no judge: risk ${risk.size} · ${risk.review}; the gate is the whole review`;
  const by = (s) => acts.filter((a) => a.state === s).length;
  const loose = acts.filter((a) => a.state === 'declared').map((a) => `- ${a.line.replace(/^\s*[-*]\s*/, '')}`);
  return [`risk ${risk.size} · ${risk.review} · lenses ${risk.lenses.join(', ') || 'none'} · ${acts.length} ACT: ${by('closed')} closed, ${by('declared')} declared, ${by('open')} open`, ...loose].join('\n');
};

// «modules a, b off by decision: <reason>»: the modules that share a reason go on one line.
export const offLines = (offs) => [...Map.groupBy(offs, (o) => o.reason)].map(([reason, group]) => `module${group.length > 1 ? 's' : ''} ${group.map((o) => o.name).join(', ')} off by decision: ${reason}`);

// The `closing:` lines of the Log, which the close carries into `## Notes`; a `closing: could not run …` line goes to
// `## Could not run` instead. `closing:` is the field the line opens with, after its number and date: the phrase quoted
// inside the requirement (L1) or inside a `kit:` note is not one.
const CLOSING_FIELD = /^\s*[-*]\s*L(?!1\b)\d+(?:\s*·\s*\d{4}-\d\d-\d\d)?\s*·\s*closing:/;
const closingLines = (doc) => (doc.split(/^## Log\b.*$/m)[1] ?? '').split('\n').filter((l) => CLOSING_FIELD.test(l));
const NOT_RUN_NOTE = /^[^:]*closing:\s*could not run\b/i;
const asNote = (l) => `- ${l.replace(/^\s*[-*]\s*/, '').replace(/closing:\s*/, '')}`;
const logNotes = (doc) => closingLines(doc).filter((l) => !NOT_RUN_NOTE.test(l)).map(asNote);
const logNotRun = (doc) => closingLines(doc).filter((l) => NOT_RUN_NOTE.test(l)).map((l) => asNote(l).replace(/could not run\b[\s,:·—-]*/i, ''));

// The `kit:` lines of the Log: what the agent noted about the kit itself, carried into `## Kit notes` and the kit's notes.
export const kitLines = (doc) => (doc.split(/^## Log\b.*$/m)[1] ?? '').split('\n').filter((l) => /^\s*[-*]\s*L\d+.*\bkit:\s*\S/.test(l))
  .map((l) => l.replace(/^\s*[-*]\s*/, '').replace(/^.*?\bkit:\s*/, ''));
const kitSection = (doc) => { const k = kitLines(doc); return k.length ? ['', '## Kit notes', ...k.map((l) => `- ${l}`)] : []; };

// What this card taught about the kit, into its notes (tools/kit-notes.mjs): the checks left failed or not run, the
// waivers and the rules declared wrong in the Log, the `kit:` lines and the dealt designs the designer adjusted. Once per
// card and signal: a close run again records nothing new.
export const harvest = async (root, result) => {
  try {
    const { record } = await import('./kit-notes.mjs');
    const doc = readCard(result.cardDir) ?? '';
    const base = { repo: basename(root), card: basename(result.cardDir), once: true };
    const log = (doc.split(/^## Log\b.*$/m)[1] ?? '').split('\n');
    const notes = [
      ...result.checks.filter((c) => ['failed', 'could not run'].includes(c.state)).map((c) => ({ kind: c.state === 'failed' ? 'failed' : 'could-not-run', key: `close:${c.label}`, text: c.detail ?? c.state })),
      ...log.flatMap((l) => { const m = l.match(/\bdeclared · ([\w-]+) · (.*)$/); return m ? [{ kind: 'waiver', key: `declared:${m[1]}`, text: m[2] }] : []; }),
      ...log.flatMap((l) => { const m = l.match(/\brule (\S+) is wrong:\s*(.*)$/); return m ? [{ kind: 'rule-wrong', key: `rule:${m[1]}`, text: m[2] }] : []; }),
      ...kitLines(doc).map((text) => ({ kind: 'agent', key: 'agent', text })),
      ...textOf(join(result.cardDir, 'rondas.md')).split('\n').flatMap((l) => { const m = l.match(/[^.]*\(adjusted[^)]*\)[^.]*/i); return m ? [{ kind: 'adjusted', key: 'design:adjusted', text: m[0] }] : []; }),
    ];
    for (const n of notes) record({ ...base, ...n });
    return notes.length;
  } catch { return 0; }
};

// The head of the PR a maintainer reads first: what the card changes (its title and specs), why (the requirement, cut at
// 600 characters), and what breaks for whoever already uses it (`## Changes to existing behavior`).
const bulletsOf = (text) => (text ?? '').split('\n').filter((l) => /^\s*[-*]\s+\S/.test(l)).map((l) => l.trim());
export const prHead = (doc) => {
  const title = doc.match(/^#\s+(.+)$/m)?.[1]?.trim() ?? '';
  const specs = bulletsOf(sectionOf(doc, 'Specs')).filter((l) => /^[-*]\s+S\d+\b/.test(l));
  const why = requirementOf(doc).replace(/^\s*(?:[-*]\s*)?L1\s*·\s*/, '').replace(/\s+/g, ' ').trim();
  // sectionOf matches a heading by its first word: `## Changes to existing behavior`.
  const breaking = bulletsOf(sectionOf(doc, 'Changes')).filter((l) => !/^[-*]\s+none\b/i.test(l));
  return ['## What', [title, ...specs].filter(Boolean).join('\n') || 'none', '', '## Why', why ? (why.length > 600 ? `${why.slice(0, 600)}…` : why) : 'none',
    '', '## Breaking changes', breaking.length ? breaking.join('\n') : 'none', ''];
};

// A frozen test file edited only in its wording: the same spec tags, and the same code once comments, test titles, assertion
// messages and docstrings are blanked and every plain name is replaced by the order it first appears in. Every other string
// counts as data: `parse("12")` → `parse("13")`, another email or date of the fixture, is an edit for a person, as is a
// changed number, operator, member or a different variable checked; a name translated the same way everywhere is not.
// Measured: a card that translated ~400 test files left 195 such edits for a person to confirm.
const TITLE_CALL = /\b(?:test|it|describe|suite|context|specify|scenario|group|testWidgets|Deno\s*\.\s*test|t\s*\.\s*(?:test|run))(?:\s*\.\s*(?:only|skip|todo|each|concurrent|serial|fails|sequential)\b)*\s*(?:\([^()]*\))?\s*\(\s*$/;
const MESSAGE_CALL = /\b(?:assert(?:\s*\.\s*\w+)?|expect|ok|equal|strictEqual|deepEqual|deepStrictEqual|notEqual|notStrictEqual|notDeepEqual|match|doesNotMatch|throws|rejects|fail|assertEquals|assertTrue|assertFalse)\s*$/;
const STRING_AT = /"""[\s\S]*?"""|'''[\s\S]*?'''|`(?:\\.|[^`\\])*`|"(?:\\.|[^"\\\n])*"|'(?:\\.|[^'\\\n])*'/y;
const COMMENT_AT = /\/\*[\s\S]*?(?:\*\/|$)|\/\/[^\n]*|#[^\n]*/y;
const CLOSES_CALL = /\s*\)/y;
const ENDS_LINE = /[ \t]*(?:\n|$)/y;
const at = (re, text, i) => { re.lastIndex = i; return re.exec(text); };
const wordingBlanked = (text) => {
  const out = [];
  const calls = [];
  let tail = '';
  let line = '';
  const emit = (s) => {
    out.push(s);
    tail = (tail + s).slice(-200);
    const nl = s.lastIndexOf('\n');
    line = nl < 0 ? line + s : s.slice(nl + 1);
  };
  let i = 0;
  while (i < text.length) {
    const comment = at(COMMENT_AT, text, i);
    if (comment && !(comment[0][0] === '#' && /[\w$.]$/.test(tail))) { i += comment[0].length; continue; }
    const str = at(STRING_AT, text, i);
    if (str) {
      const end = i + str[0].length;
      const title = TITLE_CALL.test(tail);
      const message = /,\s*$/.test(tail) && at(CLOSES_CALL, text, end) !== null && MESSAGE_CALL.test(calls.at(-1) ?? '');
      const pyMessage = /^\s*assert\b.*,\s*$/.test(line) && at(ENDS_LINE, text, end) !== null;
      const docstring = /^(?:"""|''')/.test(str[0]) && /:\s*$/.test(tail);
      emit(title || message || pyMessage || docstring ? '""' : str[0]);
      i = end;
      continue;
    }
    const c = text[i];
    if (c === '(') calls.push(tail.match(/[\w$.\s]*$/)[0]);
    else if (c === ')') calls.pop();
    emit(c);
    i++;
  }
  return out.join('');
};
const codeShape = (text) => {
  const names = new Map();
  return wordingBlanked(String(text).replace(/\r\n?/g, '\n'))
    .replace(/("(?:\\.|[^"\\\n])*"|'(?:\\.|[^'\\\n])*'|`(?:\\.|[^`\\])*`)|(\.)?\b([A-Za-z_$][\w$]*)\b/g, (m, str, dot, w) => {
      if (str || dot) return m;
      if (!names.has(w)) names.set(w, `«${names.size}»`);
      return names.get(w);
    })
    .replace(/\s+/g, '');
};
export const sameTestShape = (before, after) => {
  const tags = (s) => [...(String(s).match(new RegExp(FROZEN_TAG.source, 'g')) ?? [])].sort().join(' ');
  return tags(before) !== '' && tags(before) === tags(after) && codeShape(before) === codeShape(after);
};

// A PR body takes 65 536 characters: each kind of item past CAP_ITEMS is counted in closing.md and listed whole beside it.
const CAP_ITEMS = 25;
export const PR_BODY_MAX = 65_536;

const blockOf = (root, cardDir, { doc, checks, acts, risk, asms, untagged, off, grade, manifest, base, since }) => {
  const parts = [BEGIN, ...prHead(doc), '## Passed', bullets(checks, 'passed'), '', '## Failed', bullets(checks, 'failed'), '', '## Could not run', bullets(checks, 'could not run'),
    '', '## Judge', judgeSummary(risk, acts), '', '## Assumptions',
    asms.length ? [...untagged.map((a) => `- ${a} · untested`), `${asms.length - untagged.length} of ${asms.length} tagged`].join('\n') : 'none'];
  const notes = logNotes(doc);
  if (notes.length) parts.push('', '## Notes', ...notes);
  parts.push(...kitSection(doc));
  const clones = [...declaredClones(cardDir)];
  const kept = [...declaredOverdesign(cardDir)];
  const unmutated = [...declaredUnmutated(cardDir)];
  // With `refactor-tests:`, every frozen test the card edited in place: it existed before the card and carries a spec tag.
  const refactor = gateBlock(doc)?.match(/^\s*refactor-tests\s*:\s*(\S.*)$/m)?.[1]?.trim();
  // Under `refactor-tests:` a replacement whose new test keeps every tag of the old one (and may add the card's) is a rename:
  // file or title moved, same behavior. One line of decisions, not one confirmation per test.
  const tagsOf = (s) => new Set(String(s).match(new RegExp(FROZEN_TAG.source, 'g')) ?? []);
  const isRename = (r) => { const old = tagsOf(r.name); const kept = tagsOf(r.byName); return Boolean(refactor) && old.size > 0 && [...old].every((t) => kept.has(t)); };
  const swaps = replacementsOf(doc).filter((r) => !isRename(r));
  const renames = replacementsOf(doc).filter(isRename);
  const touched = refactor ? git(root, ['diff', '--numstat', `${base}..HEAD`]).stdout.split('\n').filter(Boolean).map((l) => l.split('\t'))
    .filter(([, , f]) => f && IS_TEST_FILE.test(f) && !f.startsWith('.claude/'))
    .map(([plus, minus, f]) => ({ plus, minus, f, before: git(root, ['show', `${base}:${f}`]).stdout ?? '' }))
    .filter(({ before }) => FROZEN_TAG.test(before)) : [];
  const now = (f) => { try { return readFileSync(join(root, f), 'utf8'); } catch { return ''; } };
  const reworded = touched.filter(({ f, before }) => sameTestShape(before, now(f)));
  const edited = touched.filter((t) => !reworded.includes(t));
  const extra = [];
  const capped = (kind, lines) => {
    if (lines.length <= CAP_ITEMS) return lines;
    extra.push(`## ${kind}`, ...lines, '');
    return [...lines.slice(0, CAP_ITEMS), `- … and ${lines.length - CAP_ITEMS} more ${kind}: the whole list is in ${relativeTo(root, join(cardDir, 'closing-items.md'))}`];
  };
  if (swaps.length || clones.length || kept.length || unmutated.length || edited.length) parts.push('', '## Needs a person',
    ...capped('replaced tests', swaps.map((r) => `- replaced test: ${r.file} "${r.name}" by ${r.by} "${r.byName}" — ${r.why}; confirm the old test was wrong and the new one is not looser`)),
    ...capped('duplications (K4)', clones.map(([file, why]) => `- duplication left in place (K4): ${file} — ${why}; confirm the two copies must differ`)),
    ...capped('structures kept', kept.map(([file, why]) => `- structure kept on purpose (overdesign): ${file} — ${why}; confirm the problem asks for it`)),
    ...capped('unmutated files', unmutated.map(([file, why]) => `- left unmutated: ${file} — ${why}; confirm its tests are enough without mutation`)),
    ...capped('edited frozen tests', edited.map(({ plus, minus, f }) => `- frozen test edited by the refactor (${refactor}): ${f} (+${plus} −${minus}); confirm no assertion was loosened: \`git diff ${base.slice(0, 9)}..HEAD -- ${f}\``)));
  const items = join(cardDir, 'closing-items.md');
  if (extra.length) writeFileSync(items, `# ${cardIdOf(cardDir)} — every item of ## Needs a person\n\n${extra.join('\n')}`);
  else if (existsSync(items)) rmSync(items);
  const decisions = offLines([...off].map(([name, o]) => ({ name, reason: o.reason }))).map((l) => `- ${l}`);
  if (renames.length) decisions.push(`- tests renamed by the refactor (${refactor}): ${renames.length} replaced keeping their tags — ${[...new Set(renames.map((r) => r.file))].join(', ')}`);
  if (reworded.length) decisions.push(`- frozen tests reworded by the refactor (${refactor}): ${reworded.length} edited keeping their tags and assertions (titles, comments, strings, local names) — ` +
    `${reworded.slice(0, 10).map((t) => t.f).join(', ')}${reworded.length > 10 ? `, and ${reworded.length - 10} more` : ''}`);
  if (grade !== 'production') decisions.push(`- grade: ${grade} — ${manifest?.grade?.reason ?? ''}`);
  if (decisions.length) parts.push('', '## Decisions of the repo', ...decisions);
  const cardPath = relativeTo(root, join(cardDir, 'card.md'));
  const cost = since ? closingCost(root, null, since) : `Cost: could not run: no commit that added ${cardPath} to date the start of the card`;
  const notRun = [...logNotRun(doc)];
  if (!git(root, ['remote']).stdout?.trim()) notRun.push('- publication · no remote: no push, PR or CI');
  for (const l of risk?.lensesOff ?? []) notRun.push(`- ${l.lens} · profile ${l.profile} off: ${l.why}`);
  // A `no-visual:` declaration the gate verified is a result, not something that did not run.
  const declared = (risk?.declared ?? []).filter((d) => d.lens === 'visual').map((d) => `- visual · declared not visual: ${d.why} (no-visual passed)`);
  if (declared.length) {
    const at = parts.indexOf('## Passed') + 1;
    if (parts[at] === 'none') parts.splice(at, 1, ...declared); else parts.splice(at + 1, 0, ...declared);
  }
  if (/^Cost: could not run/.test(cost)) notRun.push('- cost — see the Cost line');
  if (notRun.length) {
    const at = parts.indexOf('## Could not run') + 1;
    if (parts[at] === 'none') parts.splice(at, 1, ...notRun); else parts.splice(at + 1, 0, ...notRun);
  }
  parts.push('', cost, END);
  return parts.join('\n');
};

const resultLine = (bad) => `Result: ${bad.length ? `not passed — ${bad.map((c) => `${c.label} (${c.state})`).join(', ')}` : 'passed'}`;

// The short closing of a poc card: what was shown, the assumptions and the capture round.
const pocBlockOf = (root, { doc, checks, grade, manifest }) => {
  const lines = (name) => (sectionOf(doc, name) ?? '').split('\n').map((l) => l.trim().replace(/^[-*]\s*/, '')).filter(Boolean);
  const specs = lines('Specs');
  const asms = specs.filter((l) => /\bASM-\d+/.test(l));
  const shown = specs.filter((l) => !asms.includes(l));
  const round = checks.find((c) => c.n === 7);
  const notRun = [...logNotRun(doc), ...(git(root, ['remote']).stdout?.trim() ? [] : ['- publication · no remote: no push, PR or CI'])];
  const notes = logNotes(doc);
  return [BEGIN, '## Shown', shown.length ? shown.map((l) => `- ${l}`).join('\n') : 'none', '', '## Assumptions',
    asms.length ? asms.map((l) => `- ${l}`).join('\n') : 'none', '', '## Capture round', `${round.state}${round.detail ? ` — ${round.detail}` : ''}`,
    '', '## Could not run', notRun.length ? notRun.join('\n') : 'none', ...(notes.length ? ['', '## Notes', ...notes] : []), ...kitSection(doc),
    '', `Grade: ${grade} — ${manifest?.grade?.reason ?? ''}`, END].join('\n');
};

const writeClosing = (root, cardDir, ctx) => {
  const path = join(cardDir, 'closing.md');
  const body = (ctx.poc ? pocBlockOf(root, ctx) : blockOf(root, cardDir, ctx)).slice(0, -END.length);
  const block = `${body}${sealLine(root, cardDir, body)}\n${END}`;
  const bad = ctx.checks.filter((c) => !['passed', 'skipped'].includes(c.state));
  if (existsSync(path)) {
    const text = readFileSync(path, 'utf8');
    const from = text.indexOf(BEGIN);
    const to = text.indexOf(END);
    if (from < 0 || to < from) return 'kept';
    const head = text.slice(0, from).replace(/^Result: .*$/m, resultLine(bad));
    writeFileSync(path, `${head}${block}${text.slice(to + END.length)}`);
    return fits(path, 'regenerated');
  }
  // closing.md is the PR body (`--body-file`) and is not edited by hand, so the attribution footer of a PR is written here,
  // outside the sealed block.
  writeFileSync(path, `# ${ctx.card} — closing\n\n${resultLine(bad)}\n\n${block}\n\n${FOOTER}\n`);
  return fits(path, 'written');
};
const fits = (path, state) => {
  const size = readFileSync(path, 'utf8').length;
  return size > PR_BODY_MAX ? `${state}, but it is ${size} characters and a PR body takes ${PR_BODY_MAX}: \`gh pr create --body-file\` will refuse it` : state;
};

